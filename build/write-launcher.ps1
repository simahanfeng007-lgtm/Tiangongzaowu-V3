# 2026-08-26 add: v3 起源版 NSIS 安装器配套 —— 生成 tiangong-launcher.ini（凌霜委托 Kimi）
# 由 build/installer.nsh 安装段调用：释放到 $PLUGINSDIR 后 ExecWait。
# 5 个 gateway token 用 CSPRNG 生成；ini 写 UTF-8 无 BOM（shell/tiangong_shell.py 以 utf-8 读取）。
# 注意：workspace_root / release_source_root 必须写在 [gateway] 段 ——
# tiangong_shell.py 的 load_launcher_config 只从 [gateway] 段读取 INI_ENV_MAP 全部键。
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$InstallDir,

    [ValidateRange(1, 65535)]
    [int]$Port = 17173
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$Rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
try {
    function New-GatewayToken {
        # 48 字节随机 → base64url，与 spawn_v3.py 的 secrets.token_urlsafe(48) 同强度
        $Bytes = New-Object byte[] 48
        $Rng.GetBytes($Bytes)
        return [Convert]::ToBase64String($Bytes).TrimEnd("=").Replace("+", "-").Replace("/", "_")
    }

    $Tokens = [ordered]@{
        desktop_token       = New-GatewayToken
        backend_token       = New-GatewayToken
        life_token          = New-GatewayToken
        communication_token = New-GatewayToken
        artifact_token      = New-GatewayToken
    }

    $AppRoot = Join-Path $InstallDir "app"
    # bug-fix: workspace_root 迁出安装目录到 %APPDATA%\tiangong-v3-qiyuan\workspace ——
    # 此前放 $InstallDir\app\backend，卸载 RMDir /r $INSTDIR 即使用户选"保留数据"也全删（2026-08-26，凌霜修 UX）
    # 与 bootstrap.py 默认 state 目录（%APPDATA%\tiangong-v3-qiyuan\runtime\gateway）同根。
    $WorkspaceRoot = Join-Path $Env:APPDATA "tiangong-v3-qiyuan\workspace"

    $Lines = New-Object System.Collections.Generic.List[string]
    $Lines.Add("; tiangong-launcher.ini - generated by TiangongV3 installer")
    $Lines.Add("[gateway]")
    $Lines.Add("port = $Port")
    foreach ($Key in $Tokens.Keys) {
        $Lines.Add("$Key = $($Tokens[$Key])")
    }
    $Lines.Add("workspace_root = $WorkspaceRoot")
    # bug-fix: release_source_root 指向 backend 负载目录而非安装根 —— 与 shell 启动的
    # cwd / ._pth 条目同层（$InstallDir\app\backend）（2026-08-26，凌霜修 UX）
    $Lines.Add("release_source_root = $(Join-Path $AppRoot "backend")")
    $Lines.Add("lifecycle = test")

    # bug-fix: ini 写到 shell\ 目录 —— tiangong_shell.py 从 shell_dir/INI_NAME 读取，
    # 写安装根会导致装机即报"缺少启动配置"（2026-08-26，凌霜修 UX）
    $IniPath = Join-Path $InstallDir "shell\tiangong-launcher.ini"
    $Utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllLines($IniPath, $Lines, $Utf8NoBom)
    Write-Host "launcher config written: $IniPath"
} finally {
    $Rng.Dispose()
}
